const PREFIX: Record<TimeOfDay, string> = { morning: 'm', afternoon: 'a', sunset: 's', night: 'n' };

function build(mood: TimeOfDay, raw: Raw[]): Quote[] {
  return raw.map(([text, author, theme], i) => ({ id: `${PREFIX[mood]}${i}`, text, author, theme }));
}

export const QUOTES: Record<TimeOfDay, Quote[]> = {
  morning: build('morning', MORNING),
  afternoon: build('afternoon', AFTERNOON),
  sunset: build('sunset', SUNSET),
  night: build('night', NIGHT),
};

export function findQuote(mood: TimeOfDay, id: string): Quote | undefined {
  return QUOTES[mood].find((q) => q.id === id);
}
